    private static void add(char c,String... rows) { GLYPHS.put(c,rows); }
    public static int width(String text,int scale) {
        int n=0; for(char c:text.toUpperCase(Locale.ROOT).toCharArray()) n+=(c==' '?4:GLYPHS.getOrDefault(c,GLYPHS.get('?'))[0].length()+1)*scale;
        return Math.max(0,n-scale);
    }
    public static void draw(Canvas canvas,String text,float x,float y,int color,int scale) {
        for(char c:text.toUpperCase(Locale.ROOT).toCharArray()) {
            if(c==' ') { x+=4*scale; continue; }
            String[] glyph=GLYPHS.getOrDefault(c,GLYPHS.get('?'));
            for(int row=0;row<7;row++) for(int col=0;col<glyph[row].length();col++) if(glyph[row].charAt(col)=='1') canvas.rect(x+col*scale,y+row*scale,scale,scale,color);
            x+=(glyph[0].length()+1)*scale;
        }
    }
